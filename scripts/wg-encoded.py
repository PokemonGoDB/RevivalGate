"""Generate workers/wondergate/src/encoded.ts: the game server's fixed Japanese texts as bytes.

Workers can't encode Shift-JIS or ISO-2022-JP, so the exact bytes are produced here with the Python
server's own modules and encoders, and embedded as Latin-1 strings (one char per byte).

    python3 scripts/wg-encoded.py [~/WonderswanCartDumper/wondergate]
"""
import json
import pathlib
import sys

repo = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else (pathlib.Path(__file__).resolve().parent.parent / "wondergate" if (pathlib.Path(__file__).resolve().parent.parent / "wondergate" / "server").is_dir() else pathlib.Path.home() / "WonderswanCartDumper/wondergate"))
sys.path.insert(0, str(repo / "server"))
import darkeyes  # noqa: E402
import digimon  # noqa: E402
import doraemon  # noqa: E402
import ggene  # noqa: E402
import mail  # noqa: E402
import portal  # noqa: E402

def b(data: bytes) -> str:
    return json.dumps(data.decode("latin-1"))

out = ["// Generated by scripts/wg-encoded.py from the Python game server. Don't edit by hand.",
       "// Each string is bytes as Latin-1 (one char per byte).", ""]
# The games page is built from docs/wondergate/progress.json: regenerate when it changes.
out.append("export const PORTAL_PAGES: Record<string, string> = {")
for path, page in portal.PAGES.items():
    out.append(f"  {json.dumps(path)}: {b(page().encode('cp932'))},")
out.append("};")
out.append(f"export const PORTAL_GAME = {b(portal.GAME_FILE.read_bytes())}; // {portal.GAME_FILE.name}, served as /game.wg")
out.append(f"export const PORTAL_MISSING = {b(portal.handle('/__missing__')[2])};")
out.append(f"export const DORAEMON_WEEKDAYS = [{', '.join(b(c.encode('shift_jis')) for c in doraemon.WEEKDAYS)}]; // Monday first")
out.append(f"export const MAIL_START_PAGE = {b(mail.START_PAGE.encode('cp932'))};")
out.append(f"export const MAIL_WELCOME_SUBJECT = {json.dumps(mail.jis('ようこそ'))};")
body_text = "ワンダーゲートのメールへようこそ。\r\nこのアドレスでメールを送受信できます。"
out.append(f"export const MAIL_WELCOME_BODY = {b(body_text.encode('iso2022_jp'))};")
out.append(f"export const DARKEYES_MERC_GONE = {b(darkeyes.sjis('その傭兵は登録を解除されました'))};")
out.append("export const GGENE_FILES: Record<string, [string, string]> = {")
for path, (game, data) in ggene.FILES.items():
    out.append(f"  {json.dumps(path)}: [{json.dumps(game)}, {b(data.encode())}],")
out.append("};")
# The bounce notice is written inline in mail.py's smtp_conn: take it from the source, with the
# recipient's address left for the Worker to put in front (in ASCII).
import ast  # noqa: E402
call = next(n for n in ast.walk(ast.parse((repo / "server" / "mail.py").read_text()))
            if isinstance(n, ast.Call) and getattr(n.func, "id", "") == "notice" and len(n.args) == 4
            and isinstance(n.args[3], ast.JoinedStr))
subject = ast.literal_eval(call.args[2])
bounce = eval(compile(ast.Expression(call.args[3]), "mail.py", "eval"), {"r": "\0R\0", "DOMAIN": mail.DOMAIN})
assert bounce.startswith("\0R\0") and bounce.count("\0R\0") == 1, "the bounce text no longer starts with the address"
out.append(f"export const MAIL_BOUNCE_SUBJECT = {json.dumps(mail.jis(subject))};")
out.append(f"export const MAIL_BOUNCE_BODY_TAIL = {b(bounce[3:].encode('iso2022_jp'))};")
out.append("export const DIGIMON_NEWS: Record<string, string> = {")
for prefix, news in digimon.NEWS.items():
    out.append(f"  {prefix}: {b(digimon.encode(news))},")
out.append("};")
dest = pathlib.Path(__file__).resolve().parent.parent / "workers/wondergate/src/encoded.ts"
dest.write_text("\n".join(out) + "\n")
print(f"wrote {dest}")
