GRAPHICS = [
    [0] * 8,                                                    # 0 blank
    [0xFF, 0x81, 0xBD, 0xA5, 0xA5, 0xBD, 0x81, 0xFF],           # 1 wall
    [0x00, 0x7E, 0x7E, 0x7E, 0x7E, 0x7E, 0x7E, 0x00],           # 2 body
    [0x3C, 0x7E, 0xDB, 0xFF, 0xFF, 0xDB, 0x66, 0x3C],           # 3 head
    [0x00, 0x18, 0x3C, 0x7E, 0x7E, 0x3C, 0x18, 0x00],           # 4 food
]


def glyph(rows):
    out = []
    for r in rows:
        b = 0
        for i, ch in enumerate(r):
            if ch == "#":
                b |= 0x80 >> (i + 1)
        out.append(b)
    return out + [0]


tiles = GRAPHICS + [glyph(G.get(chr(c), G[" "])) for c in range(0x20, 0x60)]
lines = [f"; generated by font.py: {len(tiles)} tiles, 8 bytes each (1bpp)", f"NTILES equ {len(tiles)}", "font:"]
lines += ["    db " + ", ".join(f"0x{b:02X}" for b in t) for t in tiles]
pathlib.Path(__file__).with_name("font.inc").write_text("\n".join(lines) + "\n")
